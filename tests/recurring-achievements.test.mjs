import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const root=path.resolve(import.meta.dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)];
assert.equal(scripts.length,2,'Preserve inline game scripts');
const js=scripts[0][1];
const block=(begin,end)=>{
 const start=js.indexOf(begin),finish=js.indexOf(end,start+begin.length);
 assert.ok(start>=0&&finish>start,'Missing production section: '+begin);
 return js.slice(start,finish);
};
const declarations=block('const ACHIEVEMENTS=','const KEY=');
const migration=block('function restoreAchievementRepeats(saved){','function readSave(){');
const rules=block('function achievementsProgress(a){','function gameDay(){');
const source=declarations+'\n'+migration+'\n'+rules+'\n({ACHIEVEMENTS,RECURRING_ACHIEVEMENTS,restoreAchievementRepeats,recurringAchievementValue,checkAchievements})';
const original=vm.runInNewContext(source,{state:{},earn:()=>{},note:()=>{},notify:()=>{},arcadeFx:()=>{},money:n=>'R'+n});
assert.equal(original.ACHIEVEMENTS.length,8);
assert.deepEqual(Object.keys(original.RECURRING_ACHIEVEMENTS).sort(),['fifty','million','twenty']);
assert.equal(original.RECURRING_ACHIEVEMENTS.twenty.reward,5000);
assert.equal(original.RECURRING_ACHIEVEMENTS.fifty.reward,15000);
assert.equal(original.RECURRING_ACHIEVEMENTS.million.reward,15000);
assert.match(js,/const KEY='cape-town-rentals-coastline-v3'/);
assert.match(js,/version:3/);
assert.match(js,/achievementRepeats:restoreAchievementRepeats\(s\)/);
assert.match(js,/state\.stats\.rentalRevenue=\(Number\(state\.stats\.rentalRevenue\)\|\|0\)\+payout;/);
assert.match(js,/state\.stats\.returned\+\+;state\.stats\.rentalRevenue=/);

function simulation(state){
 const receipts=[],messages=[];
 const ctx={state,earn:(value,label)=>{state.cash+=value;state.stats.earned+=value;receipts.push({value,label});},note:m=>messages.push(m),notify:m=>messages.push(m),arcadeFx:()=>{},money:n=>'R'+n};
 const api=vm.runInNewContext(source,ctx);
 return {api,receipts,messages};
}
const saved={achievements:['first','five','twenty','fifty','million'],stats:{returned:1140,earned:9300000},cash:777000};
const seeded=original.restoreAchievementRepeats(saved);
assert.equal(seeded.twenty.baseline,1140);
assert.equal(seeded.fifty.baseline,1140);
assert.equal(seeded.million.baseline,0);
assert.equal(seeded.twenty.count,0);
assert.deepEqual(Object.keys(seeded).sort(),['fifty','million','twenty']);
const state={...saved,stats:{...saved.stats,rentalRevenue:0},achievementRepeats:seeded,fleet:[],branches:[]};
const run=simulation(state);
run.api.checkAchievements();
assert.equal(state.cash,777000,'No back-pay on legacy migration');
assert.equal(run.receipts.length,0);
state.stats.returned+=19;
run.api.checkAchievements();
assert.equal(state.cash,777000);
state.stats.returned++;
run.api.checkAchievements();
assert.equal(state.cash,782000,'20-return repeat grants R5,000');
assert.equal(state.achievementRepeats.twenty.count,1);
run.api.checkAchievements();
assert.equal(state.cash,782000,'Repeated checking cannot duplicate payouts');
state.stats.returned+=30;
run.api.checkAchievements();
assert.equal(state.cash,802000,'50 returns grant an additional 20-return and 50-return repeat');
assert.equal(state.achievementRepeats.twenty.count,2);
assert.equal(state.achievementRepeats.fifty.count,1);
const cashBefore=state.cash;
state.stats.earned+=3500000;
run.api.checkAchievements();
assert.equal(state.cash,cashBefore,'Non-rental income does not trigger recurring million');
state.stats.rentalRevenue=999999;
run.api.checkAchievements();
assert.equal(state.cash,cashBefore);
state.stats.rentalRevenue=1000000;
run.api.checkAchievements();
assert.equal(state.cash,cashBefore+15000,'R1m rental revenue grants R15,000');
state.stats.rentalRevenue=3000000;
run.api.checkAchievements();
assert.equal(state.achievementRepeats.million.count,3,'Multiple delayed cycles settle exactly once');
assert.equal(state.achievementRepeats.million.earned,45000);
run.api.checkAchievements();
assert.equal(state.achievementRepeats.million.earned,45000);
const persisted=JSON.parse(JSON.stringify(state));
const resumed=original.restoreAchievementRepeats(persisted);
assert.equal(resumed.twenty.count,2,'Repeat counts persist through a save');
assert.equal(resumed.million.count,3,'Repeat counts survive a save');

const fresh={achievements:['first','five','four','ten','branches'],stats:{returned:19,earned:0,rentalRevenue:0},achievementRepeats:{},cash:10000,fleet:[],branches:[]};
const next=simulation(fresh);
next.api.checkAchievements();
assert.equal(fresh.achievementRepeats.twenty,undefined);
fresh.stats.returned=20;
next.api.checkAchievements();
assert.ok(fresh.achievements.includes('twenty'),'Original milestone still unlocks');
assert.equal(fresh.cash,35000,'Original R25,000 reward preserved');
assert.equal(fresh.achievementRepeats.twenty.baseline,20);
fresh.stats.returned=39;
next.api.checkAchievements();
assert.equal(fresh.cash,35000);
fresh.stats.returned=40;
next.api.checkAchievements();
assert.equal(fresh.cash,40000,'First repeat starts only after original unlock');
assert.equal(fresh.achievementRepeats.twenty.count,1);
assert.match(js,/Five achievements are permanent trophies/);
assert.match(js,/REPEAT /);
console.log('PASS: original eight, 3 repeat targets and rewards, saved progress migration, no historical back-pay, independent repeat counters, rental-only income, multi-cycle payout, V3 compatibility.');
