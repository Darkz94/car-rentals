import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import vm from 'node:vm';
const root=path.resolve(import.meta.dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const script=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)][0]?.[1];
assert.ok(script,'Playable source script missing');
const decl=(key,end)=>{const start=script.indexOf('const '+key+'=');const finish=script.indexOf(end,start);assert.ok(start>=0&&finish>start,key);return script.slice(start,finish+end.length);};
const sides=vm.runInNewContext(decl('CAR_IMAGES','};')+'\nCAR_IMAGES');
const tops=vm.runInNewContext(decl('CAR_IMAGES','};')+'\n'+decl('MAP_CAR_IMAGES','};')+'\nMAP_CAR_IMAGES');
const types=Array.from(vm.runInNewContext(decl('TYPES','];')+'\nTYPES'));
const customers=Array.from(vm.runInNewContext(decl('CUSTOMER_TYPES','];')+'\nCUSTOMER_TYPES'));
const contracts=Array.from(vm.runInNewContext(decl('CONTRACTS','];')+'\nCONTRACTS'));
const original=['hatch','sedan','coupe','bakkie','jeep','van','classic','muscle','truck','tow','donk','limo','partybus','bus','sport','super','hyper'];
const added=['suv','convertible','shuttle','camper','luxsuv','safari','motorhome','rally','grandtourer','armored'];
assert.equal(types.length,27);assert.equal(customers.length,78);assert.equal(contracts.length,17);
assert.equal(customers.filter(c=>!!c.vipBonus).length,8);
assert.equal(new Set(Object.values(sides)).size,27);
assert.equal(new Set(Object.values(tops)).size,27);
for(const id of original)assert.equal(sides[id],`assets/lineup-${id}-side.webp`,'Original approved art must remain unchanged');
const hashes=new Set();
for(const id of added){
  const side='assets/realistic-'+id+'-side.webp';
  const roof='assets/expansion-'+id+'-topdown.svg';
  assert.equal(sides[id],side,'Photo file mapping '+id);
  assert.equal(tops[id],roof,'Map roof mapping '+id);
  const data=fs.readFileSync(path.join(root,side));
  assert.ok(data.length>=12000,'Insufficient photoreal detail '+id);
  assert.equal(data.toString('ascii',0,4),'RIFF');
  assert.equal(data.toString('ascii',8,12),'WEBP');
  assert.equal(data.toString('ascii',12,16),'VP8X');
  assert.ok(data[20]&0x10,'Photo must have alpha channel '+id);
  const width=1+data[24]+256*data[25]+65536*data[26];
  const height=1+data[27]+256*data[28]+65536*data[29];
  assert.equal(width,900,'Showroom image width '+id);
  assert.equal(height,300,'Showroom image height '+id);
  const digest=crypto.createHash('sha256').update(data).digest('hex');
  assert.ok(!hashes.has(digest),'Real photos must not be reused');hashes.add(digest);
  const svg=fs.readFileSync(path.join(root,roof),'utf8');
  assert.match(svg,/<linearGradient id="paint"/);
  assert.match(svg,/<title>[^<]+<\/title>/);
  assert.ok(fs.existsSync(path.join(root,'assets/expansion-'+id+'-side.svg')),'Retain original side SVG '+id);
}
assert.match(script,/const KEY='cape-town-rentals-coastline-v3'/);
assert.match(script,/const VIP_OFFER_CHANCE=\.07;/);
assert.match(script,/const MAX_PENDING_CONTRACT_ENQUIRIES=3;/);
assert.match(script,/const REPUTATION_MAX_LEVEL=50/);
assert.match(script,/function finishRental\(r\)/);
console.log('PASS: ten unique transparent 900x300 photo side views, ten distinct map sprites, 17 original artwork mappings and economy/save invariants.');
